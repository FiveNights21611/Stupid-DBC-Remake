import net.fivenights.stupid_dbc.network.StupidDbcModVariables;

import javax.annotation.Nullable;

@EventBusSubscriber
public class CustomStrengthTestProcedure {
	@SubscribeEvent
	public static void onEntityAttacked(LivingIncomingDamageEvent event) {
		if (event.getEntity() != null) {
			execute(event, event.getEntity().level(), event.getEntity());
		}
	}

	public static void execute(LevelAccessor world, Entity entity) {
		execute(null, world, entity);
	}

	private static void execute(@Nullable Event event, LevelAccessor world, Entity entity) {
		if (entity == null)
			return;
		entity.hurt(new DamageSource(world.holderOrThrow(DamageTypes.GENERIC)), (float) entity.getData(StupidDbcModVariables.PLAYER_VARIABLES).Strength);
	}
}